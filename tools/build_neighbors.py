"""Build neighbors.js: which quiz places share a land border, for the connect game.

Usage:
    python3 -I tools/build_neighbors.py ne_10m_admin_0_countries.geojson \
        ne_10m_admin_1_states_provinces_lakes.geojson neighbors.js <world codes> <us codes>

Inputs are the same files tools/build_map.py uses. Two places are neighbours when their outlines
share at least `min_shared` vertices (Natural Earth draws a shared border with the same points on
both sides). For US states that's 2, which leaves out the Four Corners (Arizona/Colorado,
Utah/New Mexico touch at a single point). Countries need only 1, so very short borders like
Zambia/Botswana (about 150 m) still count.
"""
import importlib.util
import json
import os
import sys
from collections import defaultdict

_spec = importlib.util.spec_from_file_location("build_map", os.path.join(os.path.dirname(__file__), "build_map.py"))
bm = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(bm)

DECIMALS = 4  # ~10 m
# Pairs the data has touching that don't actually border (Namibia and Zimbabwe meet Zambia and
# Botswana near Kazungula but never each other).
NOT_NEIGHBORS = {("NA", "ZW")}


def adjacency(places, min_shared):
    """places: {code: [polygon, ...]} in lon/lat -> {code: sorted neighbour codes}"""
    owners = defaultdict(set)
    for code, polys in places.items():
        for p in polys:
            for ring in p:
                for x, y in ring:
                    owners[(round(x, DECIMALS), round(y, DECIMALS))].add(code)
    shared = defaultdict(int)
    for codes in owners.values():
        codes = sorted(codes)
        for i, a in enumerate(codes):
            for b in codes[i + 1:]:
                shared[a, b] += 1
    out = {code.lower(): [] for code in places}
    for (a, b), n in shared.items():
        if n >= min_shared and (a, b) not in NOT_NEIGHBORS:
            out[a.lower()].append(b.lower())
            out[b.lower()].append(a.lower())
    return {k: sorted(v) for k, v in sorted(out.items())}


def us_places(src, codes):
    fc = json.load(open(src, encoding="utf-8"))
    places = {}
    for f in fc["features"]:
        p = f["properties"]
        if p.get("iso_a2") == "US":
            code = p["iso_3166_2"].split("-", 1)[1]
            if code in codes:
                places.setdefault(code, []).extend(bm.bs.polygons(f["geometry"]))
    return places


def main():
    world_src, us_src, dst = sys.argv[1], sys.argv[2], sys.argv[3]
    world_codes = set(sys.argv[4].upper().split(","))
    us_codes = set(sys.argv[5].upper().split(","))
    world, _ = bm.load_world(world_src, world_codes)
    data = {"world": adjacency(world, 1), "us": adjacency(us_places(us_src, us_codes), 2)}
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/build_neighbors.py from Natural Earth data. Do not edit.\n")
        fh.write("// Land neighbours of each place, for the connect game.\n")
        fh.write("const NEIGHBORS = " + json.dumps(data, separators=(",", ":")) + ";\n")
    for name, adj in data.items():
        print(name, sum(len(v) for v in adj.values()) // 2, "borders,", sum(1 for v in adj.values() if not v), "with none")


if __name__ == "__main__":
    main()
